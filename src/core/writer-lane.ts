/**
 * Writer Lane — 영속 저장소를 고치는 단 하나의 줄 (ADR 0016).
 *
 * `browser.storage`에는 compare-and-swap이 없다. 여러 JS 컨텍스트가 같은 키를 다투는 한
 * 국소적인 재검사·깊이 카운터·세대 번호로는 원리적으로 닫히지 않으므로, 먼저 writer를 서비스
 * 워커 한 컨텍스트로 모으고 **그 안에서 직렬화**한다. 이 모듈이 그 직렬화만 맡는다.
 *
 * 여기가 `core`인 이유는 레인이 순수하기 때문이다 — 브라우저 API도 타이머도 만지지 않는
 * promise 사슬 하나다. 그리고 토큰을 **요구하는 쪽**(`platform`의 저장소 어댑터)과 **만드는
 * 쪽**(`runtime`의 컴포지션 루트)이 함께 이름 부를 수 있는 층이 여기뿐이다.
 *
 * 레인을 **만드는** 것은 컴포지션 루트의 몫이다. 모듈 최상단에 인스턴스를 두지 않는다 —
 * 저장소 어댑터 모듈은 화면과 서비스워커 **양쪽에 실려서**, 모듈 스코프 락은 컨텍스트마다
 * 하나씩 생겨 서로를 전혀 막지 않으면서 안전해 보인다. ADR 0016이 막으려는 그 실패 모양이다.
 */

declare const LANE: unique symbol;

/**
 * 레인을 쥐고 있다는 증표. `WriterLane.run`이 작업 콜백에 넘겨주는 것 말고는 **만들 수 없다.**
 *
 * 레인 안에서만 불려야 하는 쓰기 함수가 이 값을 인자로 요구하면, 레인 밖 호출은 컴파일
 * 오류가 된다. 주석 규약을 쓰지 않는 이유는 실측된 것이다: 명령 실행자에 이미 같은 형태의
 * 주석("마이그레이션 커밋은 이 큐를 지날 수 없다")이 있었고, 그 주석이 정확히 릴리스 r2·r3의
 * critical이 살아 있던 자리였다.
 */
export type Held = { readonly [LANE]: true };

/** 증표는 값이 아니라 **자리**다 — 담을 것이 없으므로 하나를 만들어 돌려 쓴다. */
const HELD = Object.freeze({}) as Held;

export interface WriterLane {
  /**
   * 작업을 레인에 세우고 그 결과를 돌려준다. 도착 순서 FIFO이며 우선순위는 없다.
   *
   * 중첩되는 경로(전체 초기화가 안에서 명령 실행자를 다시 부르는 것처럼)는 **다시 잡지 않고**
   * 자기가 받은 증표를 그대로 넘긴다. 재진입 가능한 레인을 만들지 않는 이유는 서비스워커에
   * `AsyncLocalStorage`가 없어 비동기 호출 사슬을 따라갈 표준 수단이 없기 때문이다 — 전역
   * 플래그로 흉내내면 레인을 쥐지 않은 병행 작업까지 재진입으로 오인해 통과시킨다.
   */
  run<T>(job: (held: Held) => Promise<T>): Promise<T>;
}

/**
 * 레인 하나를 만든다. 컴포지션 루트에서 **한 번만** 부른다.
 *
 * 계약 둘 (플랜 게이트 r1 R-2):
 * - **각 호출자는 자기 실패를 받는다.** 실패는 그것을 요청한 쪽으로만 전파된다.
 * - **레인은 언제나 전진한다.** 작업이 거부하거나 던져도 다음 작업이 실행된다.
 *
 * 두 번째가 왜 명시적 장치인가: 저장 경로는 **설계상 던진다** — 이 버전이 읽을 수 없는 상태
 * 위에 쓰라는 요청은 거부되어야 하고, 명령 검증도 거부를 던진다. 꼬리를 거부된 promise로
 * 두면 그 뒤의 모든 명령과 Backup이 서비스워커가 재시작될 때까지 막힌다. 그래서 꼬리는
 * 결과를 삼킨 사본으로 잇고, 호출자에게는 삼키지 않은 원본을 돌려준다.
 */
export function createWriterLane(): WriterLane {
  let tail: Promise<void> = Promise.resolve();

  return {
    run<T>(job: (held: Held) => Promise<T>): Promise<T> {
      const result = tail.then(() => job(HELD));
      tail = result.then(swallow, swallow);
      return result;
    },
  };
}

function swallow(): void {}
